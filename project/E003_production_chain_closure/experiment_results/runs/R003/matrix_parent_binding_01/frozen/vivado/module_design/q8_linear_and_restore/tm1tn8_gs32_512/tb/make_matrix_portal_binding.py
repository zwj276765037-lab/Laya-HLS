#!/usr/bin/env python3
"""Emit the real resident/ledger binding from its checked port declarations."""
from pathlib import Path
import re

MODULE = Path(__file__).resolve().parents[1]
resident = (MODULE / 'rtl/tm4tn8_matrix_resident_v2.sv').read_text()
header = resident.split('module tm4tn8_matrix_resident_v2 (', 1)[1].split(');', 1)[0]
ports = []
direction, width = '', ''
for token in header.split(','):
    token = token.strip()
    match = re.fullmatch(r'(input|output)\s+logic\s*((?:\[[^]]+\]\s*)*)(\w+)', token)
    if match:
        direction, width, name = match.groups()
    else:
        assert re.fullmatch(r'\w+', token), token
        name = token
    ports.append((direction, width.strip(), name))
assert len(ports) > 100
external = [p for p in ports if p[2].startswith(('m_axi_', 'a_', 'w_'))]
internal = [p for p in ports if p[2] not in {'clk', 'rst_n', 'cancel'} and p not in external]
lease_ports = [p for p in external if p[2].startswith(('a_acquire_', 'a_release_', 'w_lease_', 'w_release_'))]
text = '''`timescale 1ns/1ps
// Generated by tb/make_matrix_portal_binding.py. This instantiates the actual
// matrix datapath and producer ledger; cache ports remain real lease endpoints.
// The enclosing 13BO arbitration and LOAD/quant/G service hub are separate ports.
module laya_matrix_portal_binding_v1 (
  input logic clk,rst_n,service_cancel,
  input logic service_command_valid,
  output logic service_command_ready,
  input logic [8191:0] service_command,
  output logic service_completion_valid,
  input logic service_completion_ready,
  output logic [4095:0] service_completion,
  input logic physical_debt_zero,
  input logic [12:0][63:0] latched_bo_base,latched_bo_span,
  output logic [1:0][3:0] output_bo_role,
'''
text += ',\n'.join(f'  {d} logic {w} {n}'.replace('logic  ', 'logic ') for d, w, n in external)
text += '\n);\n  import laya_compute_portal_layout_v1::*;\n'
text += ''.join(f'  logic {w} {n};\n'.replace('logic  ', 'logic ') for _, w, n in internal)
text += ''.join(f'  logic {w} matrix_{n};\n'.replace('logic  ', 'logic ') for _, w, n in lease_ports)
text += '''  logic active,rejected,command_ok,ledger_ready,ledger_admitted,ledger_reject;
  logic parent_a_ready,parent_a_admitted,parent_a_rejected,parent_a_live,parent_a_pinned;
  logic parent_w_ready,parent_w_admitted,parent_w_rejected,parent_w_live,parent_w_pinned;
  logic parent_cancel,view_retired;
  logic [4:0] parent_a_next,parent_w_next;
  logic [15:0] parent_status,merged_status;
  logic [63:0] parent_rank,parent_bad,merged_rank,merged_bad;
  logic ledger_target_invalidated,ledger_parent_complete,ledger_parent_error;
  logic [2:0] ledger_ps_state,ledger_dst_state;
  logic [15:0] ledger_checked_rows,ledger_covered_rows;
  logic [31:0] ledger_claims,ledger_retirements,ledger_publications;
  logic [1:0][64:0] physical_end,region_end,region_limit;
  logic qkv;
  logic [15:0] result_status;
  logic [31:0] result_detail;
  always_comb begin
    qkv=service_command[(CONTEXT+4)*8+:8]==8'h30;
    output_bo_role[0]=service_command[OUT0_ROLE*8+:4];
    output_bo_role[1]=service_command[OUT1_ROLE*8+:4];
    command_ok=command_frame_ok(service_command) && service_command[OP_STATUS*8+:16]==3 &&
      (service_command[ROWS*8+:8]==1 || service_command[ROWS*8+:8]==4) &&
      service_command[ROW_BLOCK*8+:8]<16 && !service_cancel;
    cfg_bo_base=0;cfg_bo_span=0;cfg_region_base=0;cfg_region_span=0;
    physical_end=0;region_end=0;region_limit=0;
    for(int s=0;s<2;s++)begin
      if(s==0 || qkv)begin
        if(output_bo_role[s]<6 || output_bo_role[s]>12)command_ok=0;
        else begin
          cfg_bo_base[s]=latched_bo_base[output_bo_role[s]];
          cfg_bo_span[s]=latched_bo_span[output_bo_role[s]];
          physical_end[s]={1'b0,cfg_bo_base[s]}+{1'b0,cfg_bo_span[s]};
          region_end[s]={1'b0,service_command[(OUTPUT_RANGES+24*s+8)*8+:64]}+
                        {1'b0,service_command[(OUTPUT_RANGES+24*s+16)*8+:64]};
          region_limit[s]={1'b0,cfg_bo_base[s]}+
                         {1'b0,service_command[(OUTPUT_RANGES+24*s+8)*8+:64]};
          cfg_region_base[s]=region_limit[s][63:0];
          cfg_region_span[s]=service_command[(OUTPUT_RANGES+24*s+16)*8+:64];
          if(physical_end[s][64] || region_end[s][64] || region_limit[s][64] ||
             service_command[(OUTPUT_RANGES+24*s)*8+:64]!=cfg_bo_span[s] ||
             region_end[s]>{1'b0,cfg_bo_span[s]} || cfg_region_base[s][5:0]!=0 ||
             cfg_region_span[s]==0)command_ok=0;
        end
      end else if(service_command[(OUTPUT_RANGES+24*s)*8+:192]!=0)command_ok=0;
    end
    if(qkv && (output_bo_role[0]!=8 || output_bo_role[1]!=9))command_ok=0;
    command_ok=command_ok && parent_a_admitted && parent_w_admitted && ledger_admitted;
  end
  assign service_command_ready=!active && !rejected && !service_cancel && physical_debt_zero &&
      cfg_ready && ledger_ready && parent_a_ready && parent_w_ready;
  assign cfg_valid=service_command_valid && service_command_ready && command_ok;
  assign cfg_owner_admitted=ledger_admitted;
  assign cfg_target_invalidated=ledger_target_invalidated;
  assign cfg_K=service_command[K*8+:16];assign cfg_N=service_command[N*8+:16];
  assign cfg_rows=service_command[ROWS*8+:3];assign cfg_row_block_base=service_command[ROW_BLOCK*8+:4];
  assign cfg_numeric_identity=service_command[IDENTITY*8+:672];
  assign cfg_linear_context=service_command[CONTEXT*8+:96];
  assign cfg_source_ref=service_command[SOURCE_REF*8+:64];assign cfg_a_ref=service_command[A_REF*8+:64];
  assign cfg_w_ref=service_command[W_REF*8+:64];assign cfg_ps_ref=service_command[PS_REF*8+:64];
  assign cfg_dst_ref=service_command[DST_REF*8+:64];
  assign cfg_w_model_identity=service_command[MODEL_IDENTITY*8+:3328];
  assign cfg_a_slot=service_command[A_SLOT*8];assign cfg_w_slot=service_command[W_SLOT*8];
  assign cfg_bias_kind=service_command[BIAS_KIND*8];
  assign cfg_a_epoch=service_command[A_EPOCH*8+:32];assign cfg_w_epoch=service_command[W_EPOCH*8+:32];
  assign cfg_weight_key=service_command[WEIGHT_KEY*8+:16];
  assign cfg_row_stride_bytes=service_command[ROW_STRIDE*8+:64];
  assign cfg_batch_stride_bytes=service_command[BATCH_STRIDE*8+:64];
  assign done_ready=active && service_completion_ready && physical_debt_zero;
  assign service_completion_valid=(active && done_valid && physical_debt_zero) || rejected;
  assign parent_cancel=service_cancel || abort_parent;
  assign view_retired=active && done_valid && done_ready;
  always_comb begin
    merged_status=(parent_status==7 || done_status==7) ? 16'd7 :
      (parent_status==15 || done_status==15) ? 16'd15 : done_status;
    merged_rank=done_first_error_rank<parent_rank ? done_first_error_rank : parent_rank;
    merged_bad=done_first_error_rank<parent_rank ? done_bad_element : parent_bad;
    result_status=merged_status==0 ? 0 : merged_status==15 ? 6 : 7;
    result_detail=merged_status==0 ? 0 : {8'd7,cfg_linear_context[39:32],merged_status};
    service_completion=rejected_response(service_command,rejected ? 16'd5 : result_status,
        rejected ? 32'h04000008 : result_detail);
    if(!rejected)begin
      service_completion[RANK*8+:64]=merged_rank;
      service_completion[BAD_ELEMENT*8+:64]=merged_bad;
      service_completion[CYCLES*8+:64]=command_cycles;
      service_completion[COUNTERS*8+:32]=actual_a_reads;
      service_completion[(COUNTERS+4)*8+:32]=actual_a_returns;
      service_completion[(COUNTERS+8)*8+:32]=actual_w_reads;
      service_completion[(COUNTERS+12)*8+:32]=actual_w_returns;
      service_completion[(COUNTERS+16)*8+:32]=actual_stripes;
      service_completion[(COUNTERS+20)*8+:32]=actual_ps_commits;
      service_completion[(COUNTERS+24)*8+:32]=actual_final_copies;
      for(int s=0;s<2;s++)begin
        service_completion[(COUNTERS+28+s*4)*8+:32]=actual_aw_count[s];
        service_completion[(COUNTERS+36+s*4)*8+:32]=actual_w_count[s];
        service_completion[(COUNTERS+44+s*4)*8+:32]=actual_b_count[s];
      end
      if(merged_status==0 && !service_cancel)begin
        service_completion[ELEMENTS*8+:32]=32'(cfg_rows)*32'(cfg_N);
        service_completion[UNIT*8+:8]=1;
        // A response publishes this actual view extent; the caller separately
        // retires the typed parent only after all views and leases finish.
        service_completion[RETIRE_FLAGS*8+1]=owner_retire_success || ledger_dst_state==2;
      end
    end
  end
  always_ff @(posedge clk)begin
    if(!rst_n)begin
      active<=0;rejected<=0;parent_status<=0;parent_rank<='1;parent_bad<='1;
    end
    else begin
      if(service_command_valid && service_command_ready)begin
        active<=command_ok;rejected<=!command_ok;
      end
      if(cfg_valid && cfg_row_block_base==0)begin
        parent_status<=0;parent_rank<='1;parent_bad<='1;
      end else if(active && done_valid)begin
        parent_status<=merged_status;parent_rank<=merged_rank;parent_bad<=merged_bad;
      end
      if(service_completion_valid && service_completion_ready)begin active<=0;rejected<=0;end
    end
  end
  tm4tn8_matrix_owner_ledger_v2 ledger(
    .clk,.rst_n,.claim_valid(cfg_valid),.claim_ready(ledger_ready),
    .claim_admitted(ledger_admitted),.claim_reject(ledger_reject),
    .claim_K(cfg_K),.claim_N(cfg_N),.claim_rows(cfg_rows),.claim_row_block_base(cfg_row_block_base),
    .claim_numeric_identity(cfg_numeric_identity),.claim_parent_context(cfg_linear_context),
    .claim_source_ref(cfg_source_ref),.claim_a_ref(cfg_a_ref),.claim_w_ref(cfg_w_ref),
    .claim_ps_ref(cfg_ps_ref),.claim_dst_ref(cfg_dst_ref),.claim_model_identity(cfg_w_model_identity),
    .invalidate_valid(owner_invalidate_valid),.cancel_parent(parent_cancel),.retire_valid(owner_retire_valid),
    .retire_ready(owner_retire_ready),.retire_error(owner_retire_error),
    .retire_success(owner_retire_success),.retire_debt_zero(physical_debt_zero),
    .retire_row_block_base(owner_retire_row_block_base),.retire_rows(owner_retire_rows),
    .ps_state(ledger_ps_state),.dst_state(ledger_dst_state),.target_invalidated(ledger_target_invalidated),
    .parent_complete(ledger_parent_complete),.parent_error(ledger_parent_error),
    .checked_rows(ledger_checked_rows),.covered_rows(ledger_covered_rows),
    .claims(ledger_claims),.view_retirements(ledger_retirements),.parent_publications(ledger_publications));
  tm4tn8_matrix_resident_v2 matrix(
'''
# The single real resident uses local grants; only parent layers reach the
# actual caches. Read/return ports remain direct and retain complete parent L.
parent_connections = []
for kind, prefix, acquire, release, widths in [
        ('a', 'a', 'acquire', 'release', (1011, 865)),
        ('w', 'w', 'lease', 'release', (4209, 801))]:
    acq_names = [n for d, _, n in lease_ports if d == 'output' and n.startswith(prefix+'_'+acquire+'_') and n != prefix+'_'+acquire+'_valid']
    rel_names = [n for d, _, n in lease_ports if d == 'output' and n.startswith(prefix+'_'+release+'_') and n != prefix+'_'+release+'_valid']
    # RTL declaration order is the frozen typed-handle order in the contract.
    acq_local = ','.join('matrix_'+n for n in acq_names)
    acq_physical = ','.join(acq_names)
    rel_local = ','.join('matrix_'+n for n in rel_names)
    rel_physical = ','.join(rel_names)
    text += f'  logic [{widths[0]-1}:0] parent_{kind}_acquire_handle;\n'
    text += f'  logic [{widths[1]-1}:0] parent_{kind}_release_handle;\n'
    text += f'  assign {{{acq_physical}}}=parent_{kind}_acquire_handle;\n'
    text += f'  assign {{{rel_physical}}}=parent_{kind}_release_handle;\n'
    text += f'''  laya_parent_{kind}_lease_v2 parent_{kind}(
    .clk,.rst_n,.cancel(parent_cancel),.view_valid(cfg_valid),.view_ready(parent_{kind}_ready),
    .view_admitted(parent_{kind}_admitted),.view_rejected(parent_{kind}_rejected),.view_command(service_command),
    .view_done(view_retired),.physical_debt_zero(physical_debt_zero && a_read_debt_zero),
    .parent_live(parent_{kind}_live),.parent_pinned(parent_{kind}_pinned),.cancel_done(),
    .origin_generation(),.active_generation(),.next_row(parent_{kind}_next),
    .local_acquire_valid(matrix_{prefix}_{acquire}_valid),
    .local_acquire_ready(matrix_{prefix}_{acquire}_ready),
    .local_acquire_done(matrix_{prefix}_{acquire}_done),.local_acquire_error(matrix_{prefix}_{acquire}_error),
    .local_acquire_handle({{{acq_local}}}),.physical_acquire_valid({prefix}_{acquire}_valid),
    .physical_acquire_ready({prefix}_{acquire}_ready),.physical_acquire_done({prefix}_{acquire}_done),
    .physical_acquire_error({prefix}_{acquire}_error),.physical_acquire_handle(parent_{kind}_acquire_handle),
    .local_release_valid(matrix_{prefix}_{release}_valid),.local_release_ready(matrix_{prefix}_{release}_ready),
    .local_release_done(matrix_{prefix}_{release}_done),.local_release_error(matrix_{prefix}_{release}_error),
    .local_release_handle({{{rel_local}}}),.physical_release_valid({prefix}_{release}_valid),
    .physical_release_ready({prefix}_{release}_ready),.physical_release_done({prefix}_{release}_done),
    .physical_release_error({prefix}_{release}_error),.physical_release_handle(parent_{kind}_release_handle));
'''
# Move the resident instance after the parent layers for readable generated RTL.
text = text.replace('  tm4tn8_matrix_resident_v2 matrix(\n', '')
text += '  tm4tn8_matrix_resident_v2 matrix(\n'
text += ',\n'.join('    .cancel(service_cancel)' if n == 'cancel' else
                  '    .'+n+'(matrix_'+n+')' if any(n == p[2] for p in lease_ports) else
                  '    .'+n for _, _, n in ports)
text += '\n  );\nendmodule\n'
(MODULE / 'rtl/laya_matrix_portal_binding_v1.sv').write_text(text)
print('FULL_CURRENT_MATRIX_PORTAL_BINDING_GENERATED ports=' + str(len(external)))
