#pragma once

#include <cstdint>

namespace laya::full::front_observed {

// Frozen 32-bit word schema for the bounded B1/S128 production front chain.
// All multiword integers use low word first. Owner slots are HIDDEN bank0,
// LN_GAMMA bank0, HIDDEN bank1. No field is an expected value or a control input.
constexpr uint32_t kMagic = 0x314f464c; // "LFO1" in little-endian memory
constexpr uint32_t kCpuMagic = 0x314f4643; // "CFO1"
constexpr uint32_t kVersion = 1;
constexpr unsigned kGlobalWords = 64;
constexpr unsigned kOwnerWords = 112;
constexpr unsigned kOwnerCount = 3;
constexpr unsigned kWords = kGlobalWords + kOwnerCount * kOwnerWords;
constexpr unsigned kCpuWords = 432;

enum Cpu : unsigned {
  PROFILE = 400, DESCRIPTOR_VALID, ADMITTED, IMPORTS_STARTED,
  IMPORTS_COMMITTED, RAW_VERIFIED, EXPECTED_RAW_CRC, ACTUAL_RAW_CRC,
  RAW_BYTES_LO, RAW_BYTES_HI, RAW_ELEMENTS_LO, RAW_ELEMENTS_HI,
  IMPORT_ROWS_COVERED, DESCRIPTOR_ERROR_OFFSET, IMPORT_BAD_ELEMENT_LO,
  IMPORT_BAD_ELEMENT_HI, REACHED_PHASE, FIRST_ERROR_STAGE,
  FIRST_ERROR_OPERATOR, FIRST_ERROR_TASK_ID, CLEANUP_ATTEMPTED,
  CLEANUP_COMPLETED, SCAN_COMPLETE, REQUEST_CRC_VALID,
  DESCRIPTOR_CRC_VALID, EXPECTED_REQUEST_CRC, ACTUAL_REQUEST_CRC,
  EXPECTED_DESCRIPTOR_CRC, ACTUAL_DESCRIPTOR_CRC
};

enum Global : unsigned {
  MAGIC = 0, VERSION, WORDS, STATUS, DETAIL, BAD_ELEMENT_LO,
  BAD_ELEMENT_HI, LAST_EXEC_STATUS, LAST_EXEC_DETAIL,
  LAST_CLEANUP_STATUS, LAST_CLEANUP_DETAIL, REQUEST_VALID,
  MODEL_HEADER_VALID, DIAGNOSTIC_IDENTITY_VALID, DIAGNOSTIC_SHAPE_VALID,
  DIAGNOSTIC_REQUEST_LO, DIAGNOSTIC_REQUEST_HI,
  DIAGNOSTIC_GENERATION_LO, DIAGNOSTIC_GENERATION_HI,
  DIAGNOSTIC_B, DIAGNOSTIC_S, INPUT_REQUEST_LO, INPUT_REQUEST_HI,
  INPUT_GENERATION_LO, INPUT_GENERATION_HI, INPUT_B, INPUT_S,
  SESSION_GENERATION_LO, SESSION_GENERATION_HI,
  LAST_ACCEPTED_REQUEST_LO, LAST_ACCEPTED_REQUEST_HI,
  TASKS_RETIRED, LAST_TASK_ID, OWNER_CLAIMS, OWNER_LEASES,
  EMB_TOKEN_CALLS, LOAD_LN_PARAMS_CALLS, LN_EMB_CALLS,
  ENCODER_LAYERS, DECISION_LAYERS, OUTPUT_ID, OUTPUT_BANK,
  OUTPUT_EPOCH, OUTPUT_REGION, OUTPUT_STAGE, OUTPUT_LAYER,
  OUTPUT_BATCH, OUTPUT_ROW_SPACE, OUTPUT_ROW0, OUTPUT_ROWS,
  OUTPUT_WIDTH, OUTPUT_CONTENT, LIVE_READERS,
  INCOMPLETE_OWNERS
};

enum Owner : unsigned {
  FOUND = 0, SLOT, REF_ID, REF_BANK, REF_EPOCH, MAX_CLAIMED_EPOCH,
  REGION, STAGE, LAYER, BATCH, ROW_SPACE, ROW0, ROWS, WIDTH,
  CONTENT, STATE, READERS, VALID, IDENTITY_B, IDENTITY_S,
  IDENTITY_REQUEST_LO, IDENTITY_REQUEST_HI,
  IDENTITY_GENERATION_LO, IDENTITY_GENERATION_HI,
  MODEL_TAG0, NUMERIC_TAG0 = MODEL_TAG0 + 4,
  LAYOUT_TAG0 = NUMERIC_TAG0 + 4, BUILD_TAG0 = LAYOUT_TAG0 + 4,
  COVERAGE0 = 48
};

} // namespace laya::full::front_observed
