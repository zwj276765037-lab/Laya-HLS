#!/usr/bin/env python3
"""Generate the fixed L13M v1/LYMP v1 production SystemVerilog package.

The selected C header is the only model-package input.  Byte zero is emitted
at the low bit index of each packed SystemVerilog vector.
"""

import argparse
import hashlib
import re
from pathlib import Path


def parse_array(text: str, name: str, count: int) -> bytes:
    match = re.search(rf"\b{name}\s*\[{count}\]\s*=\s*\{{([^}}]+)\}}", text)
    if not match:
        raise ValueError(f"missing {name}[{count}]")
    values = [int(token, 0) for token in re.findall(r"0x[0-9a-fA-F]+|\d+", match.group(1))]
    if len(values) != count or any(value > 0xFF for value in values):
        raise ValueError(f"invalid {name}: expected {count} bytes")
    return bytes(values)


def parse_sizes(text: str) -> list[int]:
    match = re.search(r"\bkFullModelBoSizes\s*\[5\]\s*=\s*\{([^}]+)\}", text)
    if not match:
        raise ValueError("missing kFullModelBoSizes[5]")
    values = [int(token, 0) for token in re.findall(r"0x[0-9a-fA-F]+|\d+", match.group(1))]
    if len(values) != 5 or any(value < 1 or value > 0xFFFFFFFF for value in values):
        raise ValueError("invalid kFullModelBoSizes[5]")
    return values


def put(target: bytearray, offset: int, value: int, width: int) -> None:
    target[offset:offset + width] = value.to_bytes(width, "little")


def sv_literal(payload: bytes) -> str:
    return f"{len(payload) * 8}'h" + payload[::-1].hex()


def generate(header: Path) -> str:
    raw = header.read_bytes()
    text = raw.decode()
    model = parse_array(text, "kFullModelTag", 16)
    numeric = parse_array(text, "kFullNumericTag", 16)
    layout = parse_array(text, "kFullLayoutTag", 16)
    build = parse_array(text, "kFullBuildTag", 16)
    source = parse_array(text, "kFullSourceSha256", 32)
    sizes = parse_sizes(text)

    identity = bytearray(416)
    identity[0:16] = model
    identity[16:32] = numeric
    identity[32:48] = layout
    identity[48:64] = build
    put(identity, 64, 0x4D33314C, 4)
    put(identity, 68, 1, 2)
    put(identity, 70, 416, 2)
    put(identity, 72, 0, 4)
    put(identity, 76, 1, 4)
    identity[80:112] = source
    put(identity, 112, 5, 4)
    put(identity, 116, 16, 4)
    put(identity, 120, 128, 4)
    for index, (role, size) in enumerate(zip((0, 2, 3, 4, 5), sizes)):
        entry = 128 + 16 * index
        put(identity, entry, role, 4)
        put(identity, entry + 4, 1, 4)
        put(identity, entry + 8, size, 8)

    aux = bytearray(128)
    aux[0:4] = b"LYMP"
    put(aux, 4, 1, 2)
    put(aux, 6, 0, 2)
    put(aux, 8, 128, 4)
    put(aux, 12, 13, 4)
    put(aux, 16, 1, 4)
    aux[32:48] = model
    aux[48:64] = numeric
    aux[64:80] = layout
    aux[80:96] = build
    aux[96:128] = source

    sha = hashlib.sha256(raw).hexdigest()
    return f"""`timescale 1ns/1ps
// Generated by tools/generate_laya_model_identity_sv.py.
// Input: {header.name}; sha256={sha}
package laya_model_identity_13bo_generated_v1;
  localparam int L13M_BYTES=416,LYMP_BYTES=128;
  localparam logic [63:0] MODEL_BYTES_EMBEDDING=64'd{sizes[0]};
  localparam logic [63:0] MODEL_BYTES_W_Q0=64'd{sizes[1]};
  localparam logic [63:0] MODEL_BYTES_W_Q1=64'd{sizes[2]};
  localparam logic [63:0] MODEL_BYTES_W_SCALE=64'd{sizes[3]};
  localparam logic [63:0] MODEL_BYTES_AUX=64'd{sizes[4]};
  localparam logic [3327:0] L13M_CANONICAL={sv_literal(identity)};
  localparam logic [1023:0] LYMP_CANONICAL={sv_literal(aux)};

  // Structural checks select the fixed L13M/LYMP production dialect.  Model
  // tags, source digest, and exact BO sizes are checked by canonical equality
  // so a structurally valid identity for another package reports E_MODEL.
  function automatic logic l13m_structure_ok(input logic [3327:0] p);
    logic valid;
    valid=p[64*8+:32]==32'h4d33314c && p[68*8+:16]==16'd1 &&
      p[70*8+:16]==16'd416 && p[72*8+:32]==0 && p[76*8+:32]==32'd1 &&
      p[112*8+:32]==32'd5 && p[116*8+:32]==32'd16 &&
      p[120*8+:32]==32'd128 && p[124*8+:32]==0 && p[208*8+:1664]==0;
    for(int i=0;i<5;i++)begin
      case(i)
        0:valid=valid && p[(128+16*i)*8+:32]==32'd0;
        1:valid=valid && p[(128+16*i)*8+:32]==32'd2;
        2:valid=valid && p[(128+16*i)*8+:32]==32'd3;
        3:valid=valid && p[(128+16*i)*8+:32]==32'd4;
        4:valid=valid && p[(128+16*i)*8+:32]==32'd5;
      endcase
      valid=valid && p[(132+16*i)*8+:32]==32'd1;
    end
    return valid;
  endfunction

  function automatic logic l13m_canonical_ok(input logic [3327:0] p);
    return p==L13M_CANONICAL;
  endfunction

  function automatic logic l13m_numeric_tags_ok(input logic [3327:0] p,
      input logic [671:0] numeric_identity);
    return p[0+:512]==numeric_identity[20*8+:512] &&
      numeric_identity[20*8+:512]==L13M_CANONICAL[0+:512];
  endfunction

  function automatic logic lymp_structure_ok(input logic [1023:0] p);
    return p[0+:32]==32'h504d594c && p[4*8+:16]==16'd1 &&
      p[6*8+:16]==0 && p[8*8+:32]==32'd128 &&
      p[12*8+:32]==32'd13 && p[16*8+:32]==32'd1 && p[20*8+:96]==0;
  endfunction

  function automatic logic lymp_canonical_ok(input logic [1023:0] p);
    return p==LYMP_CANONICAL;
  endfunction
endpackage
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    rendered = generate(args.header.resolve())
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(rendered)


if __name__ == "__main__":
    main()
